# Writes terms.luna from the glossary in locales/enUS.json: every `TERM_<KEY>` that has a `TERM_<KEY>_TEXT` is a
# term, with its name and its text. Run it after a term is added to the locales:
#   python addons/OrdaenTooltips/terms.py
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
locale = json.load(open(os.path.join(here, 'locales', 'enUS.json'), encoding='utf8'))
keys = [key[5:] for key in locale if key.startswith('TERM_') and ('%s_TEXT' % key) in locale]


def member(key):
    return ''.join(part.capitalize() for part in key.split('_'))


out = [
    '// The glossary: the terms a part of a tooltip can name, each with its name and its text in the locales. A',
    "// «%s» in either is the amount the part speaks of.",
    '// Generated by terms.py from the `TERM_` keys of locales/enUS.json: never edited by hand.',
    'import Locale from "@/locales"',
    '',
    'public enum Term {',
]
out += ['  %s = "%s",' % (member(key), key.lower()) for key in keys]
out += [
    '}',
    '',
    'public struct Entry {',
    '  name: string',
    '  text: string',
    '}',
    '',
    'public function glossary(term: Term): Entry {',
    '  switch (term) {',
]
out += ['    case Term::%s: return { name: Locale::TERM_%s, text: Locale::TERM_%s_TEXT }' % (member(key), key, key)
        for key in keys]
out += ['  }', '}', '']
open(os.path.join(here, 'terms.luna'), 'w', encoding='utf8', newline='\n').write('\n'.join(out))
print('%d terms' % len(keys))
