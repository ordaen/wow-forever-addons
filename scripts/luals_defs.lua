-- LuaLS definitions (a "library" of ---@meta files) from the structured Forever API (api.json, see
-- api_import.lua M.Structured), so lua-language-server knows exactly what the game has: typed documented
-- functions, widget classes with their inheritance (worked out from the dumped method sets), the dumped
-- Blizzard objects, the WowEvent names, and every other global. Written to api/forever/luals/ by the import
-- (and `--rebuild`), for the current version only. Lua 5.1, no dependencies; specs use M.Generate.
local M = {}

local KEYWORDS = {}
for word in ([[and break do else elseif end false for function if in local nil not or repeat return then true
	until while]]):gmatch("%a+") do
	KEYWORDS[word] = true
end

local BASIC = {
	number = "number",
	bool = "boolean",
	boolean = "boolean",
	string = "string",
	cstring = "string",
	stringView = "string",
	luaIndex = "integer",
	fileID = "integer",
	table = "table",
	["function"] = "function",
	userdata = "userdata",
}

local function sortedKeys(t)
	local keys = {}
	for k in pairs(t or {}) do
		keys[#keys + 1] = k
	end
	table.sort(keys)
	return keys
end

local function isIdentifier(name)
	return type(name) == "string" and name:match("^[%a_][%w_]*$") ~= nil and not KEYWORDS[name]
end

local function paramName(name, index)
	if not isIdentifier(name) then
		return "arg" .. index
	end
	return name
end

--- Widget types as classes: each type's parent is the type whose methods are the largest strict subset of
--- its own (Button's are Frame's plus more), so `Button` can be passed where a `Frame` is expected.
function M.WidgetHierarchy(widgets)
	local sets, sizes = {}, {}
	for name, methods in pairs(widgets) do
		if methods then
			local set, n = {}, 0
			for _, m in ipairs(methods) do
				if not set[m] then
					set[m], n = true, n + 1
				end
			end
			sets[name], sizes[name] = set, n
		end
	end
	local parent = {}
	for name, set in pairs(sets) do
		local best
		for other, otherSet in pairs(sets) do
			if other ~= name and sizes[other] < sizes[name] then
				local subset = true
				for m in pairs(otherSet) do
					if not set[m] then
						subset = false
						break
					end
				end
				if subset and (not best or sizes[other] > sizes[best] or (sizes[other] == sizes[best] and other < best)) then
					best = other
				end
			end
		end
		parent[name] = best
	end
	return parent, sets
end

local function newWriter(header)
	local out = {
		"---@meta",
		"-- Generated by scripts/api-import.sh (scripts/luals_defs.lua) from " .. header .. ". Do not edit.",
		"",
	}
	return out, function(line)
		out[#out + 1] = line
	end
end

--- Generate the definition files. Returns { [filename] = content }.
---@param api table the structured API (api.json)
---@param folder string the version folder, for the headers
function M.Generate(api, folder)
	local widgets = api.widgets or {}
	local parent, sets = M.WidgetHierarchy(widgets)
	local unknownTypes = {}

	local function luaType(t)
		if BASIC[t] then
			return BASIC[t]
		end
		if sets[t] then
			return t
		end
		local simple = type(t) == "string" and t:match("^Simple(%u%w*)$")
		if simple and sets[simple] then
			return simple -- SimpleTexture -> Texture
		end
		if type(t) == "string" and t:match("^[%a_][%w_]*$") then
			unknownTypes[t] = true
			return t
		end
		return "any"
	end

	-- Blizzard marks arguments that have a default as non-nilable. Dumps that don't record defaults
	-- (meta.docsDefaults false) can't tell those apart, so there every argument after the first is optional
	-- (forever-lint's FL3 likewise reports too few arguments only once defaults are known).
	local knowsDefaults = api.meta and api.meta.docsDefaults
	local function docLines(write, info)
		for i, a in ipairs(info.args or {}) do
			local optional = (a.nilable or a.default or (not knowsDefaults and i > 1)) and "?" or ""
			write(("---@param %s%s %s"):format(paramName(a.name, i), optional, luaType(a.type)))
		end
		for i, r in ipairs(info.returns or {}) do
			write(("---@return %s%s %s"):format(luaType(r.type), r.nilable and "?" or "", paramName(r.name, i)))
		end
	end

	local function params(info)
		local names = {}
		for i, a in ipairs(info.args or {}) do
			names[#names + 1] = paramName(a.name, i)
		end
		return table.concat(names, ", ")
	end

	-- Undocumented: any arguments, any results (without the @return, LuaLS would take the result as nil).
	local function untyped(write, fullName)
		write("---@return any ...")
		write("function " .. fullName .. "(...) end")
	end

	local files = {}
	local source = "api/forever/" .. folder

	-- events.lua: every documented event name, for RegisterEvent and friends.
	do
		local out, write = newWriter(source)
		write("---Every event Blizzard documents on this Forever version.")
		write("---@alias WowEvent")
		for _, name in ipairs(sortedKeys(api.events)) do
			write(('---| "%s"'):format(name))
		end
		write("")
		files["events.lua"] = table.concat(out, "\n")
	end

	-- widgets.lua: one class per widget type, methods it adds to its parent's.
	do
		local out, write = newWriter(source)
		local creators = {
			CreateTexture = "Texture",
			CreateFontString = "FontString",
			CreateMaskTexture = "MaskTexture",
			CreateLine = "Line",
			CreateAnimationGroup = "AnimationGroup",
			CreateAnimation = "Animation",
		}
		local eventMethods = {
			RegisterEvent = "---@param event WowEvent\n---@return boolean registered",
			UnregisterEvent = "---@param event WowEvent",
			IsEventRegistered = "---@param event WowEvent\n---@return boolean registered",
			RegisterUnitEvent = "---@param event WowEvent\n---@param unit1? string\n---@param unit2? string\n"
				.. "---@return boolean registered",
		}
		for _, name in ipairs(sortedKeys(sets)) do
			local p = parent[name]
			-- each class in its own block: Lua allows at most 200 locals at once in a chunk
			write("do")
			write(("---@class %s%s"):format(name, p and (" : " .. p) or ""))
			write(("local %s = {}"):format(name))
			local inherited = p and sets[p] or {}
			for _, method in ipairs(sortedKeys(sets[name])) do
				if not inherited[method] and isIdentifier(method) then
					if eventMethods[method] then
						write(eventMethods[method])
						write(("function %s:%s(event, ...) end"):format(name, method))
					elseif creators[method] then
						write("---@return " .. creators[method])
						write(("function %s:%s(...) end"):format(name, method))
					else
						untyped(write, name .. ":" .. method)
					end
				end
			end
			write("end")
			write("")
		end
		-- BackdropTemplate (CreateFrame(..., "BackdropTemplate")): BackdropTemplateMixin's functions.
		local mixin = api.namespaces and api.namespaces.BackdropTemplateMixin
		if mixin then
			write("---@class BackdropTemplate")
			write("local BackdropTemplate = {}")
			for _, key in ipairs(sortedKeys(mixin)) do
				if mixin[key] == "function" and isIdentifier(key) then
					untyped(write, "BackdropTemplate:" .. key)
				end
			end
			write("")
		end
		files["widgets.lua"] = table.concat(out, "\n")
	end

	-- functions.lua: namespaces (C_Map, Enum...) with their members; documented ones typed.
	local functions = api.functions or {}
	do
		local out, write = newWriter(source)
		for _, ns in ipairs(sortedKeys(api.namespaces)) do
			if isIdentifier(ns) then
				write(ns .. " = {}")
				for _, key in ipairs(sortedKeys(api.namespaces[ns])) do
					if isIdentifier(key) then
						local kind = api.namespaces[ns][key]
						local full = ns .. "." .. key
						if kind == "function" then
							local info = functions[full]
							if info then
								docLines(write, info)
								write(("function %s(%s) end"):format(full, params(info)))
							else
								untyped(write, full)
							end
						elseif kind == "number" then
							write(full .. " = 0")
						elseif kind == "string" then
							write(full .. ' = ""')
						elseif kind == "boolean" then
							write(full .. " = false")
						else
							write("---@type table")
							write(full .. " = {}")
						end
					end
				end
				write("")
			end
		end
		files["functions.lua"] = table.concat(out, "\n")
	end

	-- objects.lua: the dumped Blizzard objects (Minimap, MinimapCluster.Tracking...), each a class with the
	-- members the dump saw; deeper paths become typed fields of their parent.
	local objectClass = {}
	for _, path in ipairs(sortedKeys(api.objects)) do
		if not path:find("#", 1, true) then
			objectClass[path] = path:gsub("%.", "_") .. "Object"
		end
	end
	do
		local out, write = newWriter(source)
		for _, path in ipairs(sortedKeys(objectClass)) do
			local members = api.objects[path]
			local widgetType = members["<objectType>"]
			local base = widgetType and sets[widgetType] and (" : " .. widgetType) or ""
			write("do") -- one block per class: Lua allows at most 200 locals at once in a chunk
			write(("---@class %s%s"):format(objectClass[path], base))
			if members["<truncated>"] or members["<forbidden>"] then -- members not (all) known
				write("---@field [string] any")
			end
			local methods = {}
			for _, key in ipairs(sortedKeys(members)) do
				local kind = members[key]
				local child = objectClass[path .. "." .. key]
				if key == "<ref>" or key:sub(1, 1) == "<" or not isIdentifier(key) then -- luacheck: ignore 542
					-- markers and unnamed children: nothing to declare
				elseif child then
					write(("---@field %s %s"):format(key, child))
				elseif kind == "function" then
					if not (widgetType and sets[widgetType] and sets[widgetType][key]) then
						methods[#methods + 1] = key
					end
				elseif kind == "<ref>" or (type(kind) == "string" and objectClass[kind]) then
					write(("---@field %s %s"):format(key, objectClass[kind] or "table"))
				else
					write(("---@field %s %s"):format(key, BASIC[kind] or "table"))
				end
			end
			local class = objectClass[path]
			write(("local %s = {}"):format(class))
			for _, method in ipairs(methods) do
				untyped(write, class .. ":" .. method)
			end
			if not path:find(".", 1, true) then
				write(("---@type %s"):format(class))
				write(("%s = %s"):format(path, class))
			end
			write("end")
			write("")
		end
		files["objects.lua"] = table.concat(out, "\n")
	end

	-- globals.lua: every other global. Documented functions typed; CreateFrame returns the widget class.
	do
		local out, write = newWriter(source)
		local frameTypes = {}
		for name in pairs(sets) do
			local p = name
			while p do
				if p == "Frame" then
					frameTypes[#frameTypes + 1] = name
					break
				end
				p = parent[p]
			end
		end
		table.sort(frameTypes)
		if api.namespaces and api.namespaces.BackdropTemplateMixin then
			-- A frame made with the BackdropTemplate also has its functions (SetBackdrop...).
			for _, t in ipairs(frameTypes) do
				write(("---@class %sWithBackdrop : %s, BackdropTemplate"):format(t, t))
			end
			for _, t in ipairs(frameTypes) do
				write(('---@overload fun(frameType: "%s", name: string?, parent: any?, template: "BackdropTemplate", '
					.. "id: integer?): %sWithBackdrop"):format(t, t))
			end
		end
		for _, t in ipairs(frameTypes) do
			write(('---@overload fun(frameType: "%s", name?: string, parent?: any, template?: string, id?: integer): %s')
				:format(t, t))
		end
		write("---@param frameType string")
		write("---@param name? string")
		write("---@param parent? any")
		write("---@param template? string")
		write("---@param id? integer")
		write("---@return Frame")
		write("function CreateFrame(frameType, name, parent, template, id) end")
		write("")
		for _, name in ipairs(sortedKeys(api.globals)) do
			local kind = api.globals[name]
			if isIdentifier(name) and name ~= "CreateFrame" and not api.namespaces[name] and not objectClass[name] then
				if kind == "function" then
					local info = functions[name]
					if info then
						docLines(write, info)
						write(("function %s(%s) end"):format(name, params(info)))
					else
						untyped(write, name)
					end
				elseif kind == "string" then
					write(name .. ' = ""')
				elseif kind == "number" then
					write(name .. " = 0")
				elseif kind == "boolean" then
					write(name .. " = false")
				else
					write("---@type table")
					write(name .. " = {}")
				end
			end
		end
		write("")
		files["globals.lua"] = table.concat(out, "\n")
	end

	-- types.lua: type names the documentation uses that aren't widgets or Lua types (structures, enums,
	-- unit tokens...): known names, any shape, so signatures read well without false alarms.
	do
		local out, write = newWriter(source)
		for _, name in ipairs(sortedKeys(unknownTypes)) do
			if not sets[name] then
				write(("---@alias %s any"):format(name))
			end
		end
		write("")
		files["types.lua"] = table.concat(out, "\n")
	end
	return M.Split(files, source)
end

-- lua-language-server skips library files over its preload size (500 KB by default) without a word: the deep API
-- dump's objects.lua (14 MB) left Minimap, UIParent and GameTooltip undefined. Bigger files are cut into parts.
M.MAX_FILE = 400 * 1024

--- Cut files over M.MAX_FILE into name_1.lua, name_2.lua, ... at the top level only (outside `do ... end` blocks)
--- and never right after an annotation line (`---@...` belongs to the line after it).
---@param files table<string, string>
---@param source string for each part's header
---@return table<string, string>
function M.Split(files, source)
	local out = {}
	for name, content in pairs(files) do
		if #content <= M.MAX_FILE then
			out[name] = content
		else
			local base = name:gsub("%.lua$", "")
			local parts, current, size, depth, previous = {}, {}, 0, 0, ""
			for line in (content .. "\n"):gmatch("(.-)\n") do
				if size > M.MAX_FILE and depth == 0 and previous:sub(1, 3) ~= "---" then
					parts[#parts + 1] = table.concat(current, "\n")
					current = {
						"---@meta",
						("-- Generated by scripts/api-import.sh (scripts/luals_defs.lua) from %s, part %d. Do not edit.")
							:format(source, #parts + 1),
						"",
					}
					size = 0
				end
				current[#current + 1] = line
				size = size + #line + 1
				if line == "do" then
					depth = depth + 1
				elseif line == "end" then
					depth = depth - 1
				end
				previous = line
			end
			parts[#parts + 1] = table.concat(current, "\n")
			for i, text in ipairs(parts) do
				out[("%s_%d.lua"):format(base, i)] = text
			end
		end
	end
	return out
end

return M
