"""The talent trees for a talent's tooltip (design tooltips/spells «Talents»: «Талант · 2/5 · Оружие»), generated from
their one source, the client's tables on wago.tools (the build of wow-dev-tools tools/client-data/wago.mjs): Forever's
trait API has one tree per class and no tree names, but its Talent table still maps every rank's spell to its classic
tab (TalentTab), named in each language. Writes addons/OrdaenTooltips/talents.lua: spell -> tab, tab -> its name by
locale. Never edit the output by hand: run this again.  Run: python art/tooltip-talents.py"""
import csv
import io
import re
import urllib.request
from pathlib import Path

WAGO_MJS = Path("../wow-dev-tools/tools/client-data/wago.mjs").read_text(encoding="utf-8")
PRODUCT = re.search(r"PRODUCT = '([^']+)'", WAGO_MJS).group(1)
BUILD = re.search(r"BUILD = '([^']+)'", WAGO_MJS).group(1)
LOCALES = ["ruRU", "enUS"]


def table(name, locale):
    url = f"https://wago.tools/db2/{name}/csv?build={BUILD}&product={PRODUCT}&locale={locale}"
    request = urllib.request.Request(url, headers={"User-Agent": "ordaen-dev-tools"})
    text = urllib.request.urlopen(request, timeout=60).read().decode("utf-8")
    return list(csv.DictReader(io.StringIO(text)))


talents = table("Talent", LOCALES[0])
tabs = {locale: {row["ID"]: row["Name_lang"] for row in table("TalentTab", locale)} for locale in LOCALES}
spell_tab = {}
for row in talents:
    for i in range(9):
        spell = row.get(f"SpellRank_{i}", "0")
        if spell and spell != "0":
            spell_tab[int(spell)] = int(row["TabID"])
used = sorted(set(spell_tab.values()))
lines = [
    "-- Generated by art/tooltip-talents.py from the client's Talent and TalentTab tables; do not edit.",
    f"-- Source: wago.tools, product {PRODUCT}, build {BUILD}.",
    "-- spell (any rank of a talent) -> its tab; tab -> its name by locale.",
    "return {",
    "\ttab = {",
]
for spell in sorted(spell_tab):
    lines.append(f"\t\t[{spell}] = {spell_tab[spell]},")
lines += ["\t},", "\tname = {"]
for tab in used:
    names = ", ".join(f'{locale} = "{tabs[locale].get(str(tab), "")}"' for locale in LOCALES)
    lines.append(f"\t\t[{tab}] = {{ {names} }},")
lines += ["\t},", "}"]
Path("addons/OrdaenTooltips/talents.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{len(spell_tab)} talent ranks in {len(used)} tabs")
