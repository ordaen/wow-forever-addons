"""The races' racial abilities for a player's race tooltip (design tooltips/players «Hovering the race»), generated from
their one source, the client data (wow-dev-tools tools/client-data/out/client-data.json, extracted from wago.tools):
addons/OrdaenTooltips/racials.lua, raceID -> { spellID, classMask } pairs (classMask 0: every class; else the bit of
each class, 2^(classID - 1), that gets this variant). Names and texts come from the game at show time. Never edit the
output by hand: run this again.  Run: python art/tooltip-racials.py"""
import json
from pathlib import Path

SOURCE = Path("../wow-dev-tools/tools/client-data/out/client-data.json")
data = json.loads(SOURCE.read_text(encoding="utf-8"))
lines = [
    "-- Generated by art/tooltip-racials.py from wow-dev-tools tools/client-data; do not edit.",
    "-- Source: " + str(data.get("source", "")) + ".",
    "-- raceID -> { spellID, classMask, ... } (classMask 0: every class; else the bits 2^(classID - 1) it's for).",
    "return {",
]
for race_id, race in sorted(data["racials"].items(), key=lambda kv: int(kv[0])):
    pairs = ", ".join(f"{s['spellID']}, {s['classMask']}" for s in race["spells"])
    lines.append(f"\t[{race_id}] = {{ {pairs} }}, -- {race['enUS']}")
lines.append("}")
Path("addons/OrdaenTooltips/racials.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"{len(data['racials'])} races")
