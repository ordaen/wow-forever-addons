// The tooltips' glyphs for the game, generated from their one source, the design site's SVGs
// (wow-dev-tools design/.vitepress/theme/tooltips/data.js: GLYPHS, GLYPH_DEFS): each drawn at 64 px into one atlas
// (addons/OrdaenTooltips/assets/glyphs.tga, 8 a row) by a headless browser (design/scripts/shot.mjs), and the cell of
// each name written to addons/OrdaenTooltips/glyphs.lua. Never edit either by hand: run this again.
//   node --import ./art/register-json.mjs art/tooltip-glyphs.mjs
import { writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";

const DESIGN = resolve("../wow-dev-tools/design");
const { GLYPHS, GLYPH_DEFS } = await import(pathToFileURL(join(DESIGN, ".vitepress/theme/tooltips/data.js")));
const SIZE = 64, PER_ROW = 8;
const names = Object.keys(GLYPHS);
const rows = Math.ceil(names.length / PER_ROW);
const atlasH = 2 ** Math.ceil(Math.log2(rows * SIZE));
const cells = names.map((n, i) => `<svg style="position:absolute;left:${(i % PER_ROW) * SIZE}px;top:${Math.floor(i / PER_ROW) * SIZE}px;width:${SIZE}px;height:${SIZE}px" viewBox="0 0 16 16">${GLYPH_DEFS}${GLYPHS[n][1]}</svg>`);
const dir = mkdtempSync(join(tmpdir(), "glyphs-"));
// shot on black and on white: the difference gives each pixel's alpha exactly (anti-aliased edges kept)
const shots = ["black", "white"].map((bg) => {
	const html = join(dir, `atlas-${bg}.html`);
	writeFileSync(html, `<!doctype html><html><body style="margin:0;background:${bg}"><div style="position:relative;width:${PER_ROW * SIZE}px;height:${atlasH}px">${cells.join("")}</div></body></html>`);
	return [pathToFileURL(html).href, join(dir, `atlas-${bg}.png`)];
});
execFileSync("node", [join(DESIGN, "scripts/shot.mjs"), "--width", String(PER_ROW * SIZE), "--height", String(atlasH),
	"--wait", "300", ...shots.flat()], { stdio: "inherit" });
execFileSync("python", ["art/to-tga.py", shots[0][1], shots[1][1], "addons/OrdaenTooltips/assets/glyphs.tga",
	String(PER_ROW * SIZE), String(atlasH)], { stdio: "inherit" });
const lua = ["-- Generated by art/tooltip-glyphs.mjs from the design site's tooltip glyphs; do not edit.",
	"-- name -> its cell in assets/glyphs.tga (column, row from 0), 8 a row, 64 px each; `size` the atlas in cells.",
	"return {", `\tsize = { ${PER_ROW}, ${atlasH / SIZE} },`,
	...names.map((n, i) => `\t${/^[a-zA-Z_]\w*$/.test(n) ? n : `["${n}"]`} = { ${i % PER_ROW}, ${Math.floor(i / PER_ROW)} },`), "}", ""];
writeFileSync("addons/OrdaenTooltips/glyphs.lua", lua.join("\n"));
console.log(`${names.length} glyphs: ${names.join(" ")}`);
